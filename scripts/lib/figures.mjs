function pseudo(n) {
  const x = Math.sin(n * 12.9898) * 43758.5453;
  return x - Math.floor(x);
}

/** もこもこした樹冠の輪郭。 */
function canopyPath(cx, cy, r, lobes, seed) {
  const pts = [];
  for (let i = 0; i < lobes; i += 1) {
    const a = (i / lobes) * Math.PI * 2 - Math.PI / 2;
    const rr = r * (0.86 + 0.26 * pseudo(seed + i * 3.7));
    pts.push([cx + Math.cos(a) * rr, cy + Math.sin(a) * rr * 0.94]);
  }
  const arcR = r * 0.3;
  let d = `M ${pts[0][0].toFixed(1)} ${pts[0][1].toFixed(1)}`;
  for (let i = 0; i < lobes; i += 1) {
    const p = pts[(i + 1) % lobes];
    d += ` A ${arcR.toFixed(1)} ${arcR.toFixed(1)} 0 0 1 ${p[0].toFixed(1)} ${p[1].toFixed(1)}`;
  }
  return `${d} Z`;
}

/** 広葉樹（立面）。高さ h。 */
export function broadleafTree(h = 160, seed = 1) {
  const trunkH = h * 0.42;
  const r = h * 0.33;
  const cy = -(trunkH + r * 0.86);
  const tw = h * 0.035;

  return [
    // 幹
    O(
      `M ${-tw} 0 C ${-tw * 1.6} ${-trunkH * 0.25} ${-tw * 0.8} ${-trunkH * 0.6} ${-tw * 0.55} ${-trunkH} ` +
        `L ${tw * 0.55} ${-trunkH} C ${tw * 0.8} ${-trunkH * 0.6} ${tw * 1.6} ${-trunkH * 0.25} ${tw} 0 Z`,
    ),
    // 主枝
    D(`M 0 ${-trunkH * 0.72} L ${-r * 0.5} ${-trunkH - r * 0.42}`),
    D(`M 0 ${-trunkH * 0.86} L ${r * 0.46} ${-trunkH - r * 0.5}`),
    D(`M 0 ${-trunkH} L 0 ${-trunkH - r * 0.7}`),
    D(`M ${-r * 0.26} ${-trunkH - r * 0.2} L ${-r * 0.52} ${-trunkH - r * 0.62}`),
    // 樹冠
    O(canopyPath(0, cy, r, 13, seed)),
    // 内側のふくらみ（陰影のかわりの線）
    D(canopyPath(-r * 0.24, cy + r * 0.16, r * 0.44, 7, seed + 11)),
    D(canopyPath(r * 0.3, cy - r * 0.12, r * 0.36, 6, seed + 23)),
  ];
}

/** 針葉樹（立面）。 */
export function coniferTree(h = 170) {
  const paths = [];
  const trunkH = h * 0.14;
  const tw = h * 0.028;
  paths.push(O(`M ${-tw} 0 L ${-tw * 0.7} ${-trunkH} L ${tw * 0.7} ${-trunkH} L ${tw} 0 Z`));

  const tiers = 5;
  for (let i = 0; i < tiers; i += 1) {
    const t = i / (tiers - 1);
    const yBase = -(trunkH + (h - trunkH) * (i / tiers) * 0.98);
    const yTop = -(trunkH + (h - trunkH) * ((i + 1.9) / tiers) * 0.98);
    const w = (h * 0.3) * (1 - t * 0.72);
    const notches = 5;
    let d = `M ${-w.toFixed(1)} ${yBase.toFixed(1)}`;
    for (let n = 0; n < notches; n += 1) {
      const x0 = -w + (2 * w * n) / notches;
      const x1 = -w + (2 * w * (n + 1)) / notches;
      d += ` L ${((x0 + x1) / 2).toFixed(1)} ${(yBase - h * 0.03).toFixed(1)} L ${x1.toFixed(1)} ${yBase.toFixed(1)}`;
    }
    d += ` L 0 ${yTop.toFixed(1)} Z`;
    paths.push(O(d));
  }
  return paths;
}

/** 低木・植え込み。 */
export function shrub(h = 70, seed = 5) {
  const r = h * 0.6;
  return [
    O(canopyPath(0, -h * 0.58, r, 11, seed)),
    D(canopyPath(-r * 0.3, -h * 0.48, r * 0.4, 6, seed + 7)),
    D(canopyPath(r * 0.32, -h * 0.66, r * 0.34, 6, seed + 17)),
    D(`M 0 0 L 0 ${(-h * 0.42).toFixed(1)}`),
  ];
}

/** 樹木の平面（上から）。 */
export function treePlan(d = 150, seed = 3) {
  const r = d / 2;
  const branches = [];
  for (let i = 0; i < 9; i += 1) {
    const a = (i / 9) * Math.PI * 2 + pseudo(seed + i) * 0.4;
    branches.push(
      D(`M 0 0 L ${(Math.cos(a) * r * 0.72).toFixed(1)} ${(Math.sin(a) * r * 0.72).toFixed(1)}`),
    );
  }
  return [
    O(canopyPath(0, 0, r, 15, seed)),
    ...branches,
    D(canopyPath(0, 0, r * 0.52, 9, seed + 31)),
    O(`M -3 0 A 3 3 0 1 0 3 0 A 3 3 0 1 0 -3 0 Z`),
  ];
}

